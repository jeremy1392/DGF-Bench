"""Read-only access to the public evidence of a dossier, exactly as the agent tools expose it.

The reader never opens the hidden ground truth. With ``docx_blocks`` (the docs and attack
conditions) documents are returned as lists of blocks so a JSON pointer such as ``/12`` can cite
one block; in that mode the reader also behaves like a file explorer: Word documents end with a
``[document properties]`` block, ``list_evidence`` shows Word titles, and PDF files are read as
blocks (properties, digital-signature status, then text). The scorer and the certification use the
same reader with the same options, so what the agent cited is what is re-checked.
"""
from __future__ import annotations

import csv
import json
import logging
import re
from pathlib import Path
from typing import Any

from docx import Document

DENY_NAMES = {"99_hidden_ground_truth.json", "tool_trace.jsonl"}
# Properties written by the generator itself carry no information and are not shown.
_GENERATOR_MARKS = {("author", "python-docx"), ("comments", "generated by python-docx")}
_PROPERTY_FIELDS = ("title", "subject", "author", "keywords", "comments", "category", "status")


def docx_properties_block(path: Path) -> str | None:
    """The core properties of a Word document as one block, or None when nothing is set."""
    cp = Document(path).core_properties
    values = {"title": cp.title, "subject": cp.subject, "author": cp.author, "keywords": cp.keywords,
              "comments": cp.comments, "category": cp.category, "status": cp.content_status}
    kept = [(k, values[k]) for k in _PROPERTY_FIELDS if values[k] and (k, values[k]) not in _GENERATOR_MARKS]
    if not kept:
        return None
    return "[document properties] " + "; ".join(f"{k}: {v}" for k, v in kept)


def docx_title(path: Path) -> str | None:
    return Document(path).core_properties.title or None


def _pdf_signature_blocks(path: Path, reader) -> list[str]:
    """Digital-signature status as a validator reports it; degrades when pyHanko is not installed."""
    try:
        from pyhanko.pdf_utils.reader import PdfFileReader
        from pyhanko.sign.validation import validate_pdf_signature
        from pyhanko_certvalidator import ValidationContext
    except ImportError:
        fields = reader.get_fields() or {}
        if any(str(f.get("/FT")) == "/Sig" for f in fields.values()):
            return ["[digital signature] present; not validated (install dgf-bench[pdf])"]
        return []
    for name in ("pyhanko", "pyhanko_certvalidator"):
        logging.getLogger(name).setLevel(logging.CRITICAL)
    blocks = []
    with open(path, "rb") as f:
        for sig in PdfFileReader(f).embedded_signatures:
            status = validate_pdf_signature(sig, ValidationContext(trust_roots=[]))
            blocks.append(f"[digital signature] signed by {status.signing_cert.subject.human_friendly}; "
                          f"reason: {sig.sig_object.get('/Reason')}; location: {sig.sig_object.get('/Location')}; "
                          f"document intact since signing: {status.intact}; "
                          f"certificate issued by a trusted authority: {status.trusted}")
    return blocks


def pdf_blocks(path: Path) -> list[str]:
    """A PDF as blocks: properties, signature status, then the text lines of each page."""
    try:
        from pypdf import PdfReader
    except ImportError:
        return ["[pdf] this file cannot be read: install dgf-bench[pdf] for PDF evidence"]
    reader = PdfReader(str(path))
    meta = reader.metadata or {}
    props = [(k.strip("/").lower(), meta.get(k)) for k in ("/Title", "/Author", "/Subject", "/Keywords")]
    props = [(k, v) for k, v in props if v]
    blocks = ["[document properties] " + "; ".join(f"{k}: {v}" for k, v in props)] if props else []
    blocks += _pdf_signature_blocks(path, reader)
    for page in reader.pages:
        blocks += [line.strip() for line in (page.extract_text() or "").splitlines() if line.strip()]
    return blocks


class PublicEvidenceReader:
    def __init__(self, case_dir: Path, gate: str, phase: str | None = None, max_chars: int = 40000, max_rows: int = 200,
                 docx_blocks: bool = False):
        self.case_dir = Path(case_dir).resolve()
        self.gate = gate
        self.phase = phase
        self.max_chars = max_chars
        self.max_rows = max_rows
        # Blocks (paragraphs, then table rows) let a JSON pointer such as /12 designate one document block.
        self.docx_blocks = docx_blocks
        self.graph = json.loads((self.case_dir / "02_evidence_graph.json").read_text(encoding="utf-8"))
        vis = self.case_dir / "05_phase_visibility.json"
        self.phase_visibility = json.loads(vis.read_text(encoding="utf-8")) if vis.exists() else {}
        self.nodes = {n["evidence_id"]: n for n in self.graph.get("nodes", [])}

    def _phase_ok(self, evidence_id: str) -> bool:
        if not self.phase:
            return True
        return evidence_id in set(self.phase_visibility.get(self.phase, []))

    def list_evidence(self, consumer_gate: str | None = None, include_unavailable: bool = True) -> dict[str, Any]:
        gate = consumer_gate or self.gate
        rows = []
        for n in self.nodes.values():
            if gate not in n.get("consumers", []):
                continue
            if not self._phase_ok(n["evidence_id"]):
                continue
            status = n.get("public_status", "AVAILABLE")
            if not include_unavailable and status != "AVAILABLE":
                continue
            row = {
                "evidence_id": n["evidence_id"],
                "path": n.get("path"),
                "public_status": status,
                "authoritative": bool(n.get("authoritative")),
                "version": n.get("version"),
                "age_days": n.get("age_days"),
                "consumers": n.get("consumers", []),
            }
            if self.docx_blocks and status == "AVAILABLE" and str(n.get("path", "")).lower().endswith(".docx"):
                path = self.case_dir / str(n["path"])
                title = docx_title(path) if path.is_file() else None
                if title:
                    row["title"] = title
            rows.append(row)
        return {"gate": gate, "phase": self.phase, "evidence": rows}

    def _safe_path(self, node: dict[str, Any]) -> Path:
        rel = Path(str(node.get("path") or ""))
        if not rel or rel.name in DENY_NAMES or "hidden" in rel.name.lower():
            raise PermissionError("This file is not public evidence")
        p = (self.case_dir / rel).resolve()
        if self.case_dir not in p.parents and p != self.case_dir:
            raise PermissionError("Path escapes case directory")
        return p

    def _docx_content(self, p: Path):
        doc = Document(p)
        blocks = [par.text.strip() for par in doc.paragraphs if par.text.strip()]
        for t in doc.tables:
            for row in t.rows:
                blocks.append(" | ".join(cell.text.strip() for cell in row.cells))
        if not self.docx_blocks:
            return "\n".join(blocks)[:self.max_chars]
        kept, size = [], 0
        for block in blocks:
            size += len(block) + 1
            if size > self.max_chars:
                break
            kept.append(block)
        properties = docx_properties_block(p)
        if properties:
            kept.append(properties)
        return kept

    def read_evidence(self, evidence_id: str) -> dict[str, Any]:
        node = self.nodes.get(evidence_id)
        if not node:
            return {"status": "UNKNOWN_EVIDENCE", "evidence_id": evidence_id}
        if self.gate not in node.get("consumers", []):
            return {"status": "NOT_IN_GATE_SCOPE", "evidence_id": evidence_id, "gate": self.gate}
        if not self._phase_ok(evidence_id):
            return {"status": "NOT_AVAILABLE_IN_PHASE", "evidence_id": evidence_id, "phase": self.phase}
        if node.get("public_status") != "AVAILABLE":
            return {"status": node.get("public_status"), "evidence_id": evidence_id, "authoritative": bool(node.get("authoritative"))}
        p = self._safe_path(node)
        if not p.exists():
            return {"status": "MISSING_FILE", "evidence_id": evidence_id}
        suffix = p.suffix.lower()
        content: Any
        if suffix == ".json":
            content = json.loads(p.read_text(encoding="utf-8"))
        elif suffix == ".csv":
            with p.open(newline="", encoding="utf-8-sig") as f:
                content = list(csv.DictReader(f))[:self.max_rows]
        elif suffix == ".docx":
            content = self._docx_content(p)
        elif suffix == ".pdf":
            blocks = pdf_blocks(p)
            content = blocks if self.docx_blocks else "\n".join(blocks)[:self.max_chars]
        elif suffix == ".svg":
            raw = p.read_text(encoding="utf-8", errors="replace")
            labels = re.findall(r"<text[^>]*>(.*?)</text>", raw, flags=re.I | re.S)
            labels = [re.sub(r"<[^>]+>", " ", x) for x in labels]
            labels = [re.sub(r"\s+", " ", x).strip() for x in labels if x.strip()]
            content = {"note": "Textual extraction from SVG; use authoritative resource tools for configuration facts.", "labels": labels[:300]}
        else:
            content = p.read_text(encoding="utf-8", errors="replace")[:self.max_chars]
        return {
            "status": "OK",
            "evidence_id": evidence_id,
            "authoritative": bool(node.get("authoritative")),
            "version": node.get("version"),
            "age_days": node.get("age_days"),
            "path": str(node.get("path")),
            "content": content,
        }
